// The WhatsApp apply chat's words, for Windmill (pnpm whatsapp:copy).
//
// The chat runs in Windmill (integrations/windmill/talent/lib/whatsapp.ts),
// which cannot import the site's content. This writes what it needs into
// integrations/windmill/talent/lib/whatsapp-copy.json: the chat's own copy
// (src/content/pages/whatsapp-apply.ts), the quick form's questions and
// answer labels (quick-apply.ts), the jobs form's consent line and
// confirmation (jobs.ts) and the privacy notice's address, per language.
// --check fails when the file is stale (CI), so the chat and the form say
// the same things.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { importTs, root } from "./lib/register-ts.mjs";

const OUT = resolve(root, "integrations/windmill/talent/lib/whatsapp-copy.json");

const { whatsappApplyCopy, WHATSAPP_LANGUAGE_MENU, WHATSAPP_LANGUAGE_PROMPT, WHATSAPP_CONSENT_VERSION, PREFILL_TAG, whatsappNoFee } =
  await importTs("src/content/pages/whatsapp-apply.ts");
const { quickApplyCopy, WORK_OPTIONS, areaOptions } = await importTs("src/content/pages/quick-apply.ts");
const { jobsCopy } = await importTs("src/content/pages/jobs.ts");
const { localePath } = await importTs("src/lib/i18n.ts");
const BASE_URL = "https://www.vayasyaseva.com";

const AREAS = areaOptions(null, "ask");

const locales = Object.fromEntries(
  Object.entries(whatsappApplyCopy).map(([locale, chat]) => {
    const quick = quickApplyCopy[locale];
    const form = jobsCopy[locale].form;
    const option = (id) => ({ id, label: quick.labels[id] });
    return [
      locale,
      {
        welcome: chat.welcome,
        consent: {
          agree: form.steps.phone.agree,
          keep: form.steps.phone.keep,
          privacy: chat.consent.privacy,
          privacyUrl: `${BASE_URL}${localePath("/jobs/privacy", locale)}`,
          reply: chat.consent.reply,
        },
        declined: chat.declined,
        pick: chat.pick,
        work: { question: quick.questions.work.question, options: WORK_OPTIONS.map(option) },
        area: { question: quick.questions.area.question, options: AREAS.map(option) },
        name: chat.name,
        done: { title: form.done.title, refLabel: form.done.refLabel, body: form.done.body, noFee: whatsappNoFee(locale), calls: chat.calls },
        invalid: chat.invalid,
        media: chat.media,
        already: chat.already,
        restart: chat.restart,
        stopped: chat.stopped,
      },
    ];
  }),
);

const copy = {
  $comment: "Generated by scripts/whatsapp-copy.mjs from src/content. Edit those files and run pnpm whatsapp:copy.",
  consentVersion: WHATSAPP_CONSENT_VERSION,
  prefillTag: PREFILL_TAG,
  languagePrompt: WHATSAPP_LANGUAGE_PROMPT,
  languages: WHATSAPP_LANGUAGE_MENU,
  locales,
};
const json = `${JSON.stringify(copy, null, 2)}\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {}
  if (current !== json) {
    console.error("integrations/windmill/talent/lib/whatsapp-copy.json is stale: run pnpm whatsapp:copy");
    process.exit(1);
  }
  console.log("WhatsApp chat copy is up to date.");
} else {
  writeFileSync(OUT, json);
  console.log(`wrote ${OUT.slice(root.length + 1)}`);
}
