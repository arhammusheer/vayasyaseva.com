const COLUMN: Partial<Record<Locale, 1 | 2 | 3>> = { "hi-IN": 1, "pa-IN": 2, "kn-IN": 3 };

/** Every place's name in a page language's script; empty for English and Hinglish pages. */
export const placeNames = (locale: Locale): Readonly<Record<HomeId, string>> => {
  const column = COLUMN[locale];
  return column ? Object.fromEntries(ROWS.map((row) => [row[0], row[column]])) : {};
};

/** The ids with a name (tests check every place has one). */
export const NAMED_PLACES: readonly HomeId[] = ROWS.map(([id]) => id);

